func resourceUser() *schema.Resource {
	r := &schema.Resource{
		CreateContext: resourceUserCreate,
		ReadContext:   resourceUserRead,
		DeleteContext: resourceUserDelete,
		UpdateContext: resourceUserUpdate,

		Importer: &schema.ResourceImporter{
			StateContext: resourceUserImport,
		},

		Schema: map[string]*schema.Schema{
			"username": {
				Type:        schema.TypeString,
				Required:    true,
				Description: "Username used to log in to Portainer. Must be unique within the Portainer instance.",
			},
			"password": {
				Type:        schema.TypeString,
				Optional:    true,
				Sensitive:   true,
				Description: "Password for the Portainer user. Required for non-LDAP users; must be omitted for LDAP users. Stored in state as a sensitive value.",
			},
			"role": {
				Type:         schema.TypeInt,
				Optional:     true,
				Default:      2,
				ValidateFunc: validation.IntBetween(1, 2),
				Description:  "Portainer role of the user: 1 = administrator, 2 = standard user. Defaults to 2.",
			},
			"ldap_user": {
				Type:        schema.TypeBool,
				Optional:    true,
				Default:     false,
				Description: "Whether the user is authenticated via LDAP. When true, password must be empty and authentication is delegated to the configured LDAP server.",
			},
			"team_id": {
				Type:        schema.TypeInt,
				Optional:    true,
				Description: "Optional Portainer team ID the user is a member of. Only applicable for standard users (role = 2). Memberships managed with `portainer_team_membership` are not reflected here.",
			},
			"generate_api_key": {
				Type:        schema.TypeBool,
				Optional:    true,
				Default:     false,
				Description: "Whether to generate a Portainer API key for the user during creation. Requires password to be set.",
			},
			"api_key_description": {
				Type:        schema.TypeString,
				Optional:    true,
				Default:     "terraform-generated-api-key",
				Description: "Description applied to the generated Portainer API key. Only used when generate_api_key is true.",
			},
			"api_key_raw": {
				Type:        schema.TypeString,
				Computed:    true,
				Sensitive:   true,
				Description: "Raw API key generated by Portainer when generate_api_key is true. Computed and only available after initial creation.",
			},
		},
	}
	for k, v := range userAuthenticationMethodSchema() {
		r.Schema[k] = v
	}
	return r
}

func resourceUserCreate(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	client := meta.(*APIClient)
	username := d.Get("username").(string)
	password := d.Get("password").(string)
	role := int64(d.Get("role").(int))
	ldapUser := d.Get("ldap_user").(bool)

	if ldapUser && password != "" {
		return diag.FromErr(fmt.Errorf("cannot set password for LDAP user"))
	}
	if !ldapUser && password == "" {
		return diag.FromErr(fmt.Errorf("password is required for non-LDAP user"))
	}

	// Check if user already exists
	userList, err := listUsers(ctx, client)
	if err != nil {
		return diag.FromErr(fmt.Errorf("failed to list users: %w", err))
	}

	for _, u := range userList {
		if u.Username == username {
			d.SetId(strconv.FormatInt(u.ID, 10))
			return resourceUserUpdate(ctx, d, meta)
		}
	}

	createBody := struct {
		Username string  `json:"username"`
		Password *string `json:"password"`
		Role     int64   `json:"role"`
	}{Username: username, Role: role}
	if !ldapUser {
		createBody.Password = &password
	}

	var created portainerUser
	if err := doJSON(ctx, client, http.MethodPost, client.Endpoint+"/users", createBody, &created); err != nil {
		return diag.FromErr(fmt.Errorf("failed to create user: %w", err))
	}

	d.SetId(strconv.FormatInt(created.ID, 10))

	if teamIDInt, ok := d.GetOk("team_id"); ok {
		if role != 2 {
			return diag.FromErr(fmt.Errorf("team_id can only be used with standard users (role = 2)"))
		}
		if err := updateUserTeam(ctx, client, int(created.ID), 0, teamIDInt.(int)); err != nil {
			return diag.FromErr(err)
		}
	}

	if d.Get("generate_api_key").(bool) {
		description := d.Get("api_key_description").(string)
		if password == "" {
			return diag.FromErr(fmt.Errorf("password must be set to generate API key"))
		}

		// Authenticate as new user
		authBody := struct {
			Username string  `json:"username"`
			Password string  `json:"password"`
			APIKey   *string `json:"apiKey"`
		}{Username: username, Password: password}
		var authResp struct {
			JWT string `json:"jwt"`
		}
		if err := doJSON(ctx, client, http.MethodPost, client.Endpoint+"/auth", authBody, &authResp); err != nil {
			return diag.FromErr(fmt.Errorf("failed to authenticate as new user: %w", err))
		}

		// Portainer only creates an API key for the user it authenticates, so
		// this request carries the new user's JWT instead of the provider's
		// credentials.
		userClient := &APIClient{Endpoint: client.Endpoint, JWTToken: authResp.JWT, HTTPClient: client.HTTPClient}
		keyBody := struct {
			Description string `json:"description"`
			Password    string `json:"password"`
		}{Description: description, Password: password}
		var keyResp struct {
			RawAPIKey string `json:"rawAPIKey"`
		}
		if err := doJSON(ctx, userClient, http.MethodPost, fmt.Sprintf("%s/users/%d/tokens", client.Endpoint, created.ID), keyBody, &keyResp); err != nil {
			return diag.FromErr(fmt.Errorf("failed to generate API key: %w", err))
		}

		if err := d.Set("api_key_raw", keyResp.RawAPIKey); err != nil {
			return diag.FromErr(err)
		}
	}

	return resourceUserRead(ctx, d, meta)
}

func resourceUserRead(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	client := meta.(*APIClient)
	id, _ := strconv.ParseInt(d.Id(), 10, 64)

	var user portainerUser
	if err := doJSON(ctx, client, http.MethodGet, fmt.Sprintf("%s/users/%d", client.Endpoint, id), nil, &user); err != nil {
		if isAPINotFound(err) {
			d.SetId("")
			return nil
		}
		return diag.FromErr(fmt.Errorf("failed to read user: %w", err))
	}

	if err := d.Set("username", user.Username); err != nil {
		return diag.FromErr(err)
	}
	if err := d.Set("role", user.Role); err != nil {
		return diag.FromErr(err)
	}
	if err := setUserAuthenticationMethods(d, user); err != nil {
		return diag.FromErr(err)
	}

	// team_id tracks only the membership this resource manages. Other
	// memberships (portainer_team_membership) would otherwise show up as a
	// team_id the configuration does not have.
	if teamID := d.Get("team_id").(int); teamID != 0 {
		membership, err := findUserTeamMembership(ctx, client, int(id), teamID)
		if err != nil {
			return diag.FromErr(err)
		}
		if membership == nil {
			if err := d.Set("team_id", 0); err != nil {
				return diag.FromErr(err)
			}
		}
	}

	return nil
}

type portainerUser struct {
	ID       int64  `json:"Id"`
	Username string `json:"Username"`
	Role     int64  `json:"Role"`
	// CreatedAuthenticationMethod / LastAuthenticationMethod were added in
	// Portainer 3.0 (portainer.AuthenticationMethod: 1 = internal, 2 = LDAP,
	// 3 = OAuth). Older servers omit them, which decodes to 0.
	CreatedAuthenticationMethod int `json:"CreatedAuthenticationMethod"`
	LastAuthenticationMethod    int `json:"LastAuthenticationMethod"`
}

// userAuthMethodDescription documents the values of the 3.0 authentication
// method attributes, shared by the resource and the data source.
const userAuthMethodDescription = "One of `internal`, `ldap` or `oauth` (Portainer `portainer.AuthenticationMethod` 1/2/3). Empty on Portainer releases before 3.0, which do not report it, and when the server has not recorded it."

// authenticationMethodName maps a portainer.AuthenticationMethod value to the
// string exposed in state. 0 (unset, or a pre-3.0 server) maps to "".
func authenticationMethodName(m int) string {
	switch m {
	case 0:
		return ""
	case 1:
		return "internal"
	case 2:
		return "ldap"
	case 3:
		return "oauth"
	default:
		return strconv.Itoa(m)
	}
}

// setUserAuthenticationMethods stores the 3.0 authentication method fields.
func setUserAuthenticationMethods(d *schema.ResourceData, u portainerUser) error {
	if err := d.Set("created_authentication_method", authenticationMethodName(u.CreatedAuthenticationMethod)); err != nil {
		return err
	}
	return d.Set("last_authentication_method", authenticationMethodName(u.LastAuthenticationMethod))
}

// userAuthenticationMethodSchema returns the Computed attributes shared by
// portainer_user (resource and data source).
func userAuthenticationMethodSchema() map[string]*schema.Schema {
	return map[string]*schema.Schema{
		"created_authentication_method": {
			Type:        schema.TypeString,
			Computed:    true,
			Description: "Authentication method used when the user was created (Portainer 3.0+). " + userAuthMethodDescription,
		},
		"last_authentication_method": {
			Type:        schema.TypeString,
			Computed:    true,
			Description: "Authentication method used at the user's last login (Portainer 3.0+). " + userAuthMethodDescription,
		},
	}
}

// listUsers returns every user (GET /users).
func listUsers(ctx context.Context, client *APIClient) ([]portainerUser, error) {
	var userList []portainerUser
	if err := doJSON(ctx, client, http.MethodGet, client.Endpoint+"/users", nil, &userList); err != nil {
		return nil, err
	}
	return userList, nil
}

type userTeamMembership struct {
	ID     int `json:"Id"`
	UserID int `json:"UserID"`
	TeamID int `json:"TeamID"`
}

// findUserTeamMembership returns the user's membership in the team, or nil.
func findUserTeamMembership(ctx context.Context, client *APIClient, userID, teamID int) (*userTeamMembership, error) {
	var memberships []userTeamMembership
	if err := doJSON(ctx, client, http.MethodGet, client.Endpoint+"/team_memberships", nil, &memberships); err != nil {
		return nil, fmt.Errorf("failed to list team memberships: %w", err)
	}
	for i := range memberships {
		if memberships[i].UserID == userID && memberships[i].TeamID == teamID {
			return &memberships[i], nil
		}
	}
	return nil, nil
}

// updateUserTeam moves the user from the old team_id to the new one. A
// membership that already exists (e.g. after an import) is kept.
func updateUserTeam(ctx context.Context, client *APIClient, userID, oldTeam, newTeam int) error {
	if oldTeam != 0 {
		membership, err := findUserTeamMembership(ctx, client, userID, oldTeam)
		if err != nil {
			return err
		}
		if membership != nil {
			url := fmt.Sprintf("%s/team_memberships/%d", client.Endpoint, membership.ID)
			if err := doJSON(ctx, client, http.MethodDelete, url, nil, nil); err != nil && !isAPINotFound(err) {
				return fmt.Errorf("failed to remove user from team %d: %w", oldTeam, err)
			}
		}
	}
	if newTeam == 0 {
		return nil
	}
	membership, err := findUserTeamMembership(ctx, client, userID, newTeam)
	if err != nil || membership != nil {
		return err
	}
	body := map[string]int{"userID": userID, "teamID": newTeam, "role": 2}
	if err := doJSON(ctx, client, http.MethodPost, client.Endpoint+"/team_memberships", body, nil); err != nil {
		return fmt.Errorf("failed to assign user to team %d: %w", newTeam, err)
	}
	return nil
}

func resourceUserImport(ctx context.Context, d *schema.ResourceData, meta interface{}) ([]*schema.ResourceData, error) {
	client := meta.(*APIClient)

	// Check if the ID is a numeric ID
	if _, err := strconv.ParseInt(d.Id(), 10, 64); err == nil {
		// It's a numeric ID, so just read it
		if diags := resourceUserRead(ctx, d, meta); diags.HasError() {
			return nil, fmt.Errorf("%s", diags[0].Summary)
		}
		return []*schema.ResourceData{d}, nil
	}

	// It's not a numeric ID, so treat it as a username
	username := d.Id()
	userList, err := listUsers(ctx, client)
	if err != nil {
		return nil, fmt.Errorf("failed to list users for import: %w", err)
	}

	for _, u := range userList {
		if u.Username == username {
			d.SetId(strconv.FormatInt(u.ID, 10))
			if diags := resourceUserRead(ctx, d, meta); diags.HasError() {
				return nil, fmt.Errorf("%s", diags[0].Summary)
			}
			return []*schema.ResourceData{d}, nil
		}
	}

	return nil, fmt.Errorf("user %s not found", username)
}

func resourceUserUpdate(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	client := meta.(*APIClient)
	id, _ := strconv.ParseInt(d.Id(), 10, 64)

	// Checked before anything is changed, so a rejected team_id does not
	// leave the user half-updated.
	if d.Get("team_id").(int) != 0 && d.Get("role").(int) != 2 {
		return diag.FromErr(fmt.Errorf("team_id can only be used with standard users (role = 2)"))
	}

	if d.HasChange("password") {
		oldPw, newPw := d.GetChange("password")
		oldPwString := oldPw.(string)
		newPwString := newPw.(string)

		// Skip password update when old password is unknown (e.g. after import).
		// The Portainer API requires the current password to change it.
		if oldPwString != "" && newPwString != "" {
			pwBody := struct {
				Password    string `json:"password"`
				NewPassword string `json:"newPassword"`
			}{Password: oldPwString, NewPassword: newPwString}
			if err := doJSON(ctx, client, http.MethodPut, fmt.Sprintf("%s/users/%d/passwd", client.Endpoint, id), pwBody, nil); err != nil {
				return diag.FromErr(fmt.Errorf("failed to update password: %w", err))
			}
		}
	}

	username := d.Get("username").(string)
	role := int64(d.Get("role").(int))

	// newPassword and password are sent as null: the password is changed
	// through PUT /users/{id}/passwd above.
	updateBody := struct {
		Username    string  `json:"username"`
		Role        int64   `json:"role"`
		UseCache    bool    `json:"useCache"`
		NewPassword *string `json:"newPassword"`
		Password    *string `json:"password"`
	}{Username: username, Role: role, UseCache: true}
	if err := doJSON(ctx, client, http.MethodPut, fmt.Sprintf("%s/users/%d", client.Endpoint, id), updateBody, nil); err != nil {
		return diag.FromErr(fmt.Errorf("failed to update user: %w", err))
	}

	if d.HasChange("team_id") {
		oldTeam, newTeam := d.GetChange("team_id")
		if err := updateUserTeam(ctx, client, int(id), oldTeam.(int), newTeam.(int)); err != nil {
			return diag.FromErr(err)
		}
	}

	return resourceUserRead(ctx, d, meta)
}

func resourceUserDelete(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	client := meta.(*APIClient)
	id, _ := strconv.ParseInt(d.Id(), 10, 64)

	if err := doJSON(ctx, client, http.MethodDelete, fmt.Sprintf("%s/users/%d", client.Endpoint, id), nil, nil); err != nil {
		if isAPINotFound(err) {
			return nil
		}
		return diag.FromErr(fmt.Errorf("failed to delete user: %w", err))
	}

	return nil
}
