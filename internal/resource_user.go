func resourceUser() *schema.Resource {
	return &schema.Resource{
		CreateContext: resourceUserCreate,
		ReadContext:   resourceUserRead,
		DeleteContext: resourceUserDelete,
		UpdateContext: resourceUserUpdate,

		Importer: &schema.ResourceImporter{
			StateContext: resourceUserImport,
		},

		Schema: map[string]*schema.Schema{
			"username": {
				Type:        schema.TypeString,
				Required:    true,
				Description: "Username used to log in to Portainer. Must be unique within the Portainer instance.",
			},
			"password": {
				Type:        schema.TypeString,
				Optional:    true,
				Sensitive:   true,
				Description: "Password for the Portainer user. Required for non-LDAP users; must be omitted for LDAP users. Stored in state as a sensitive value.",
			},
			"role": {
				Type:         schema.TypeInt,
				Optional:     true,
				Default:      2,
				ValidateFunc: validation.IntBetween(1, 2),
				Description:  "Portainer role of the user: 1 = administrator, 2 = standard user. Defaults to 2.",
			},
			"ldap_user": {
				Type:        schema.TypeBool,
				Optional:    true,
				Default:     false,
				Description: "Whether the user is authenticated via LDAP. When true, password must be empty and authentication is delegated to the configured LDAP server.",
			},
			"team_id": {
				Type:        schema.TypeInt,
				Optional:    true,
				Description: "Optional Portainer team ID the user is a member of. Only applicable for standard users (role = 2). Memberships managed with `portainer_team_membership` are not reflected here.",
			},
			"generate_api_key": {
				Type:        schema.TypeBool,
				Optional:    true,
				Default:     false,
				Description: "Whether to generate a Portainer API key for the user during creation. Requires password to be set.",
			},
			"api_key_description": {
				Type:        schema.TypeString,
				Optional:    true,
				Default:     "terraform-generated-api-key",
				Description: "Description applied to the generated Portainer API key. Only used when generate_api_key is true.",
			},
			"api_key_raw": {
				Type:        schema.TypeString,
				Computed:    true,
				Sensitive:   true,
				Description: "Raw API key generated by Portainer when generate_api_key is true. Computed and only available after initial creation.",
			},
		},
	}
}

func resourceUserCreate(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	client := meta.(*APIClient)
	username := d.Get("username").(string)
	password := d.Get("password").(string)
	role := int64(d.Get("role").(int))
	ldapUser := d.Get("ldap_user").(bool)

	if ldapUser && password != "" {
		return diag.FromErr(fmt.Errorf("cannot set password for LDAP user"))
	}
	if !ldapUser && password == "" {
		return diag.FromErr(fmt.Errorf("password is required for non-LDAP user"))
	}

	// Check if user already exists
	listCtx, listErrBody := withErrorCapture(ctx)
	paramsList := users.NewUserListParams()
	paramsList.SetContext(listCtx)
	respList, err := client.Client.Users.UserList(paramsList, client.AuthInfo)
	if err != nil {
		return diag.FromErr(fmt.Errorf("failed to list users: %w", decorateSDKError(err, listErrBody)))
	}

	for _, u := range respList.Payload {
		if u.Username == username {
			d.SetId(strconv.FormatInt(u.ID, 10))
			return resourceUserUpdate(ctx, d, meta)
		}
	}

	createCtx, createErrBody := withErrorCapture(ctx)
	paramsCreate := users.NewUserCreateParams()
	paramsCreate.SetContext(createCtx)
	paramsCreate.Body = &models.UsersUserCreatePayload{
		Username: &username,
		Role:     &role,
	}
	if !ldapUser {
		paramsCreate.Body.Password = &password
	}

	respCreate, err := client.Client.Users.UserCreate(paramsCreate, client.AuthInfo)
	if err != nil {
		return diag.FromErr(fmt.Errorf("failed to create user: %w", decorateSDKError(err, createErrBody)))
	}

	d.SetId(strconv.FormatInt(respCreate.Payload.ID, 10))

	if teamIDInt, ok := d.GetOk("team_id"); ok {
		if role != 2 {
			return diag.FromErr(fmt.Errorf("team_id can only be used with standard users (role = 2)"))
		}
		if err := updateUserTeam(ctx, client, int(respCreate.Payload.ID), 0, teamIDInt.(int)); err != nil {
			return diag.FromErr(err)
		}
	}

	if d.Get("generate_api_key").(bool) {
		description := d.Get("api_key_description").(string)
		if password == "" {
			return diag.FromErr(fmt.Errorf("password must be set to generate API key"))
		}

		// Authenticate as new user
		authCtx, authErrBody := withErrorCapture(ctx)
		paramsAuth := auth.NewAuthenticateUserParams()
		paramsAuth.SetContext(authCtx)
		paramsAuth.Body = &models.AuthAuthenticatePayload{
			Username: &username,
			Password: &password,
		}

		respAuth, err := client.Client.Auth.AuthenticateUser(paramsAuth)
		if err != nil {
			return diag.FromErr(fmt.Errorf("failed to authenticate as new user: %w", decorateSDKError(err, authErrBody)))
		}

		userAuthInfo := httptransport.BearerToken(respAuth.Payload.Jwt)

		keyCtx, keyErrBody := withErrorCapture(ctx)
		paramsKey := users.NewUserGenerateAPIKeyParams()
		paramsKey.SetContext(keyCtx)
		paramsKey.ID = respCreate.Payload.ID
		paramsKey.Body = &models.UsersUserAccessTokenCreatePayload{
			Description: &description,
			Password:    &password,
		}

		respKey, err := client.Client.Users.UserGenerateAPIKey(paramsKey, userAuthInfo)
		if err != nil {
			return diag.FromErr(fmt.Errorf("failed to generate API key: %w", decorateSDKError(err, keyErrBody)))
		}

		if err := d.Set("api_key_raw", respKey.Payload.RawAPIKey); err != nil {
			return diag.FromErr(err)
		}
	}

	return resourceUserRead(ctx, d, meta)
}

func resourceUserRead(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	client := meta.(*APIClient)
	id, _ := strconv.ParseInt(d.Id(), 10, 64)

	ctx, errBody := withErrorCapture(ctx)
	params := users.NewUserInspectParams()
	params.SetContext(ctx)
	params.ID = id

	resp, err := client.Client.Users.UserInspect(params, client.AuthInfo)
	if err != nil {
		var notFound *users.UserInspectNotFound
		if errors.As(err, &notFound) {
			d.SetId("")
			return nil
		}
		return diag.FromErr(fmt.Errorf("failed to read user: %w", decorateSDKError(err, errBody)))
	}

	if err := d.Set("username", resp.Payload.Username); err != nil {
		return diag.FromErr(err)
	}
	if err := d.Set("role", resp.Payload.Role); err != nil {
		return diag.FromErr(err)
	}

	// team_id tracks only the membership this resource manages. Other
	// memberships (portainer_team_membership) would otherwise show up as a
	// team_id the configuration does not have.
	if teamID := d.Get("team_id").(int); teamID != 0 {
		membership, err := findUserTeamMembership(ctx, client, int(id), teamID)
		if err != nil {
			return diag.FromErr(err)
		}
		if membership == nil {
			if err := d.Set("team_id", 0); err != nil {
				return diag.FromErr(err)
			}
		}
	}

	return nil
}

type userTeamMembership struct {
	ID     int `json:"Id"`
	UserID int `json:"UserID"`
	TeamID int `json:"TeamID"`
}

// findUserTeamMembership returns the user's membership in the team, or nil.
func findUserTeamMembership(ctx context.Context, client *APIClient, userID, teamID int) (*userTeamMembership, error) {
	var memberships []userTeamMembership
	if err := doJSON(ctx, client, http.MethodGet, client.Endpoint+"/team_memberships", nil, &memberships); err != nil {
		return nil, fmt.Errorf("failed to list team memberships: %w", err)
	}
	for i := range memberships {
		if memberships[i].UserID == userID && memberships[i].TeamID == teamID {
			return &memberships[i], nil
		}
	}
	return nil, nil
}

// updateUserTeam moves the user from the old team_id to the new one. A
// membership that already exists (e.g. after an import) is kept.
func updateUserTeam(ctx context.Context, client *APIClient, userID, oldTeam, newTeam int) error {
	if oldTeam != 0 {
		membership, err := findUserTeamMembership(ctx, client, userID, oldTeam)
		if err != nil {
			return err
		}
		if membership != nil {
			url := fmt.Sprintf("%s/team_memberships/%d", client.Endpoint, membership.ID)
			if err := doJSON(ctx, client, http.MethodDelete, url, nil, nil); err != nil && !isAPINotFound(err) {
				return fmt.Errorf("failed to remove user from team %d: %w", oldTeam, err)
			}
		}
	}
	if newTeam == 0 {
		return nil
	}
	membership, err := findUserTeamMembership(ctx, client, userID, newTeam)
	if err != nil || membership != nil {
		return err
	}
	body := map[string]int{"userID": userID, "teamID": newTeam, "role": 2}
	if err := doJSON(ctx, client, http.MethodPost, client.Endpoint+"/team_memberships", body, nil); err != nil {
		return fmt.Errorf("failed to assign user to team %d: %w", newTeam, err)
	}
	return nil
}

func resourceUserImport(ctx context.Context, d *schema.ResourceData, meta interface{}) ([]*schema.ResourceData, error) {
	client := meta.(*APIClient)

	// Check if the ID is a numeric ID
	if _, err := strconv.ParseInt(d.Id(), 10, 64); err == nil {
		// It's a numeric ID, so just read it
		if diags := resourceUserRead(ctx, d, meta); diags.HasError() {
			return nil, fmt.Errorf("%s", diags[0].Summary)
		}
		return []*schema.ResourceData{d}, nil
	}

	// It's not a numeric ID, so treat it as a username
	username := d.Id()
	ctx, errBody := withErrorCapture(ctx)
	params := users.NewUserListParams()
	params.SetContext(ctx)
	resp, err := client.Client.Users.UserList(params, client.AuthInfo)
	if err != nil {
		return nil, fmt.Errorf("failed to list users for import: %w", decorateSDKError(err, errBody))
	}

	for _, u := range resp.Payload {
		if u.Username == username {
			d.SetId(strconv.FormatInt(u.ID, 10))
			if diags := resourceUserRead(ctx, d, meta); diags.HasError() {
				return nil, fmt.Errorf("%s", diags[0].Summary)
			}
			return []*schema.ResourceData{d}, nil
		}
	}

	return nil, fmt.Errorf("user %s not found", username)
}

func resourceUserUpdate(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	client := meta.(*APIClient)
	id, _ := strconv.ParseInt(d.Id(), 10, 64)

	// Checked before anything is changed, so a rejected team_id does not
	// leave the user half-updated.
	if d.Get("team_id").(int) != 0 && d.Get("role").(int) != 2 {
		return diag.FromErr(fmt.Errorf("team_id can only be used with standard users (role = 2)"))
	}

	if d.HasChange("password") {
		oldPw, newPw := d.GetChange("password")
		oldPwString := oldPw.(string)
		newPwString := newPw.(string)

		// Skip password update when old password is unknown (e.g. after import).
		// The Portainer API requires the current password to change it.
		if oldPwString != "" && newPwString != "" {
			pwCtx, pwErrBody := withErrorCapture(ctx)
			paramsPwd := users.NewUserUpdatePasswordParams()
			paramsPwd.SetContext(pwCtx)
			paramsPwd.ID = id
			paramsPwd.Body = &models.UsersUserUpdatePasswordPayload{
				Password:    &oldPwString,
				NewPassword: &newPwString,
			}

			_, err := client.Client.Users.UserUpdatePassword(paramsPwd, client.AuthInfo)
			if err != nil {
				return diag.FromErr(fmt.Errorf("failed to update password: %w", decorateSDKError(err, pwErrBody)))
			}
		}
	}

	username := d.Get("username").(string)
	role := int64(d.Get("role").(int))
	useCache := true

	ctx, errBody := withErrorCapture(ctx)
	params := users.NewUserUpdateParams()
	params.SetContext(ctx)
	params.ID = id
	params.Body = &models.UsersUserUpdatePayload{
		Username: &username,
		Role:     &role,
		UseCache: &useCache,
	}

	_, err := client.Client.Users.UserUpdate(params, client.AuthInfo)
	if err != nil {
		return diag.FromErr(fmt.Errorf("failed to update user: %w", decorateSDKError(err, errBody)))
	}

	if d.HasChange("team_id") {
		oldTeam, newTeam := d.GetChange("team_id")
		if err := updateUserTeam(ctx, client, int(id), oldTeam.(int), newTeam.(int)); err != nil {
			return diag.FromErr(err)
		}
	}

	return resourceUserRead(ctx, d, meta)
}

func resourceUserDelete(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	client := meta.(*APIClient)
	id, _ := strconv.ParseInt(d.Id(), 10, 64)

	ctx, errBody := withErrorCapture(ctx)
	params := users.NewUserDeleteParams()
	params.SetContext(ctx)
	params.ID = id

	_, err := client.Client.Users.UserDelete(params, client.AuthInfo)
	if err != nil {
		var notFoundDel *users.UserDeleteNotFound
		if errors.As(err, &notFoundDel) {
			return nil
		}
		return diag.FromErr(fmt.Errorf("failed to delete user: %w", decorateSDKError(err, errBody)))
	}

	return nil
}
