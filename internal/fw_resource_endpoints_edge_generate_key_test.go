// TestEdgeGenerateKeyResource_HappyPath: Create posts {"edgeKey":""}, keeps
// the returned key under a fixed ID; Read and destroy never call Portainer.
func TestEdgeGenerateKeyResource_HappyPath(t *testing.T) {
	t.Parallel()
	mock := NewMockServer(t)
	mock.On("POST", "/endpoints/edge/generate-key", RespondJSON(http.StatusOK, map[string]interface{}{"edgeKey": "abc123-the-key"}))

	resource.UnitTest(t, resource.TestCase{
		ProtoV5ProviderFactories: testProtoV5Factories,
		CheckDestroy: func(_ *terraform.State) error {
			if n := len(mock.Requests()); n != 1 {
				return fmt.Errorf("expected only the generate call, got %d requests", n)
			}
			return nil
		},
		Steps: []resource.TestStep{{
			Config: mockProviderConfig(mock) + `resource "portainer_endpoints_edge_generate_key" "k" {}`,
			Check: resource.ComposeTestCheckFunc(
				resource.TestCheckResourceAttr("portainer_endpoints_edge_generate_key.k", "id", "portainer-generated-edge-key"),
				resource.TestCheckResourceAttr("portainer_endpoints_edge_generate_key.k", "edge_key", "abc123-the-key"),
				func(_ *terraform.State) error {
					payload := decodeA2(t, mock.FindRequest("POST", "/endpoints/edge/generate-key"))
					if v, ok := payload["edgeKey"]; !ok || v != "" || len(payload) != 1 {
						return fmt.Errorf("expected payload {edgeKey: \"\"}, got %v", payload)
					}
					return nil
				},
			),
		}},
	})
}

func TestEdgeGenerateKeyResource_HTTPError(t *testing.T) {
	t.Parallel()
	mock := NewMockServer(t)
	mock.On("POST", "/endpoints/edge/generate-key", RespondString(http.StatusBadRequest, "application/json", `{"message":"forbidden"}`))

	resource.UnitTest(t, resource.TestCase{
		ProtoV5ProviderFactories: testProtoV5Factories,
		Steps: []resource.TestStep{{
			Config:      mockProviderConfig(mock) + `resource "portainer_endpoints_edge_generate_key" "k" {}`,
			ExpectError: regexp.MustCompile(`failed to generate edge key`),
		}},
	})
}

// TestEdgeGenerateKeyResource_UpgradeFromV300: a key generated by v3.0.0 is
// kept by this build.
func TestEdgeGenerateKeyResource_UpgradeFromV300(t *testing.T) {
	t.Parallel()
	mock := NewMockServer(t)
	mock.On("POST", "/endpoints/edge/generate-key", RespondJSON(http.StatusOK, map[string]interface{}{"edgeKey": "abc123-the-key"}))
	config := mockProviderConfig(mock) + `resource "portainer_endpoints_edge_generate_key" "k" {}`

	resource.Test(t, resource.TestCase{
		IsUnitTest: true,
		Steps: []resource.TestStep{
			{ExternalProviders: previousRelease, Config: config},
			{
				ProtoV5ProviderFactories: testProtoV5Factories,
				Config:                   config,
				ConfigPlanChecks: resource.ConfigPlanChecks{
					PreApply: []plancheck.PlanCheck{plancheck.ExpectEmptyPlan()},
				},
			},
		},
	})
}

