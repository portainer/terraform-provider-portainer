func resourceWebhook() *schema.Resource {
	return &schema.Resource{
		CreateContext: resourceWebhookCreate,
		ReadContext:   resourceWebhookRead,
		DeleteContext: resourceWebhookDelete,
		UpdateContext: resourceWebhookUpdate,
		CustomizeDiff: resourceWebhookCustomizeDiff,
		Importer: &schema.ResourceImporter{
			StateContext: schema.ImportStatePassthroughContext,
		},
		Schema: map[string]*schema.Schema{
			"endpoint_id": {
				Type:        schema.TypeInt,
				Required:    true,
				ForceNew:    true,
				Description: "Identifier of the Portainer environment (endpoint) the webhook is bound to. Changing this value forces resource recreation.",
			},
			"registry_id": {
				Type:        schema.TypeInt,
				Optional:    true,
				Description: "Identifier of the Portainer registry associated with this webhook. Used when the webhook triggers actions on images from that registry.",
			},
			"resource_id": {
				Type:     schema.TypeString,
				Required: true,
				// Deliberately not ForceNew in the schema: whether a change
				// replaces the webhook or reassigns it is decided in
				// CustomizeDiff, because only Business Edition has the
				// reassign endpoint.
				Description: "Identifier of the target resource (e.g. service ID) the webhook will act upon. Changing this value replaces the webhook unless `reassign_on_change` is set.",
			},
			"webhook_type": {
				Type:        schema.TypeInt,
				Required:    true,
				Description: "Type of webhook in Portainer: 1 = service webhook, 2 = container webhook (Business Edition only; Community Edition accepts only 1). Changing this value replaces the webhook unless `reassign_on_change` is set.",
			},
			"reassign_on_change": {
				Type:     schema.TypeBool,
				Optional: true,
				Default:  false,
				// Defaults to false so the long-standing behaviour - replace
				// the webhook - is what happens unless it is asked for. The
				// reassign endpoint does not exist in Portainer CE, so turning
				// this on there makes the apply fail.
				Description: "Whether changing `resource_id` or `webhook_type` reassigns the existing webhook instead of replacing it, keeping its token and every URL already handed out. **Business Edition only**; leave it off on CE, which has no reassign endpoint. Defaults to `false`.",
			},
			"token": {
				Type:        schema.TypeString,
				Computed:    true,
				ForceNew:    true,
				Sensitive:   true,
				Description: "Webhook token generated by Portainer. Appended to the webhook URL to authenticate trigger calls.",
			},
		},
	}
}

func resourceWebhookCreate(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	client := meta.(*APIClient)

	body := struct {
		EndpointID  int    `json:"endpointID,omitempty"`
		RegistryID  int    `json:"registryID,omitempty"`
		ResourceID  string `json:"resourceID,omitempty"`
		WebhookType int    `json:"webhookType,omitempty"`
	}{
		EndpointID:  d.Get("endpoint_id").(int),
		RegistryID:  d.Get("registry_id").(int),
		ResourceID:  d.Get("resource_id").(string),
		WebhookType: d.Get("webhook_type").(int),
	}

	var created webhookRecord
	if err := doJSON(ctx, client, http.MethodPost, client.Endpoint+"/webhooks", body, &created); err != nil {
		return diag.FromErr(fmt.Errorf("failed to create webhook: %w", err))
	}

	d.SetId(strconv.Itoa(created.ID))
	if err := d.Set("token", created.Token); err != nil {
		return diag.FromErr(err)
	}
	return nil
}

// webhookRecord is a webhook as GET /webhooks lists it. Portainer has no
// endpoint to read a single webhook, so Read looks it up in the list.
type webhookRecord struct {
	ID         int    `json:"Id"`
	Token      string `json:"Token"`
	ResourceID string `json:"ResourceId"`
	EndpointID int    `json:"EndpointId"`
	RegistryID int    `json:"RegistryId"`
	Type       int    `json:"Type"`
}

// listWebhooks lists the webhooks of a resource in an environment, or all of
// them when endpointID is 0. Business Edition rejects the call without the
// filter (it looks up environment 0); Community Edition accepts it too. The
// filter only matches webhooks with both the environment and the resource.
func listWebhooks(ctx context.Context, client *APIClient, endpointID int, resourceID string) ([]webhookRecord, error) {
	listURL := client.Endpoint + "/webhooks"
	if endpointID != 0 {
		filters, err := json.Marshal(map[string]interface{}{"EndpointID": endpointID, "ResourceID": resourceID})
		if err != nil {
			return nil, err
		}
		listURL += "?filters=" + url.QueryEscape(string(filters))
	}
	var webhooks []webhookRecord
	if err := doJSON(ctx, client, http.MethodGet, listURL, nil, &webhooks); err != nil {
		return nil, fmt.Errorf("failed to list webhooks: %w", err)
	}
	return webhooks, nil
}

func containsWebhook(webhooks []webhookRecord, id int) bool {
	for _, w := range webhooks {
		if w.ID == id {
			return true
		}
	}
	return false
}

// resourceWebhookRead used to do nothing, so a webhook deleted in Portainer
// stayed in state and its old URL kept being handed out.
func resourceWebhookRead(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	client := meta.(*APIClient)
	id, err := strconv.Atoi(d.Id())
	if err != nil {
		return diag.Errorf("invalid webhook ID %q: expected the numeric Portainer webhook ID", d.Id())
	}

	webhooks, err := listWebhooks(ctx, client, d.Get("endpoint_id").(int), d.Get("resource_id").(string))
	if err != nil {
		return diag.FromErr(err)
	}
	// Not under its resource any more: list them all, so a webhook reassigned
	// outside Terraform shows up as drift rather than as gone. Business
	// Edition cannot list without the filter, so there it counts as gone.
	if !containsWebhook(webhooks, id) {
		if all, err := listWebhooks(ctx, client, 0, ""); err == nil {
			webhooks = all
		}
	}
	for _, w := range webhooks {
		if w.ID != id {
			continue
		}
		return diag.FromErr(setFields(d, map[string]interface{}{
			"endpoint_id":  w.EndpointID,
			"resource_id":  w.ResourceID,
			"webhook_type": w.Type,
			"registry_id":  w.RegistryID,
			"token":        w.Token,
		}))
	}
	d.SetId("")
	return nil
}

func resourceWebhookUpdate(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	client := meta.(*APIClient)
	id, _ := strconv.ParseInt(d.Id(), 10, 64)

	// Pointing a webhook at a different resource has its own endpoint, which
	// keeps the webhook's token and therefore every URL already handed out.
	// Without reassign_on_change the diff above has already forced a
	// replacement, so this branch is only reached when it was asked for.
	if d.Get("reassign_on_change").(bool) && (d.HasChange("resource_id") || d.HasChange("webhook_type")) {
		payload := map[string]interface{}{
			"ResourceID":  d.Get("resource_id").(string),
			"WebhookType": d.Get("webhook_type").(int),
		}
		reassignURL := fmt.Sprintf("%s/webhooks/%d/reassign", client.Endpoint, id)
		if err := doJSON(ctx, client, http.MethodPut, reassignURL, payload, nil); err != nil {
			return diag.FromErr(fmt.Errorf("failed to reassign webhook %d: %w", id, err))
		}
	}

	if d.HasChange("registry_id") {
		body := struct {
			RegistryID int `json:"registryID,omitempty"`
		}{RegistryID: d.Get("registry_id").(int)}
		if err := doJSON(ctx, client, http.MethodPut, fmt.Sprintf("%s/webhooks/%d", client.Endpoint, id), body, nil); err != nil {
			return diag.FromErr(fmt.Errorf("failed to update webhook: %w", err))
		}
	}

	return resourceWebhookRead(ctx, d, meta)
}

func resourceWebhookDelete(ctx context.Context, d *schema.ResourceData, meta interface{}) diag.Diagnostics {
	client := meta.(*APIClient)

	if err := doJSON(ctx, client, http.MethodDelete, fmt.Sprintf("%s/webhooks/%s", client.Endpoint, d.Id()), nil, nil); err != nil && !isAPINotFound(err) {
		return diag.FromErr(fmt.Errorf("failed to delete webhook: %w", err))
	}

	d.SetId("")
	return nil
}

// resourceWebhookCustomizeDiff keeps the webhook's long-standing behaviour:
// repointing it at another resource replaces it. Business Edition can move a
// webhook in place instead, which keeps its token, but that endpoint does not
// exist in Portainer CE - so it is opt-in rather than the default.
func resourceWebhookCustomizeDiff(_ context.Context, d *schema.ResourceDiff, _ interface{}) error {
	if d.Id() == "" {
		return nil
	}
	if d.Get("reassign_on_change").(bool) {
		return nil
	}
	for _, field := range []string{"resource_id", "webhook_type"} {
		if d.HasChange(field) {
			if err := d.ForceNew(field); err != nil {
				return err
			}
		}
	}
	return nil
}
