func (r *userResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	defer func() { fwSetIDIdentity(ctx, resp.State, resp.Identity, &resp.Diagnostics) }()
	var plan userResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	client := r.client
	username := plan.Username.ValueString()
	password := plan.Password.ValueString()
	role := plan.Role.ValueInt64()
	ldapUser := plan.LDAPUser.ValueBool()

	if ldapUser && password != "" {
		resp.Diagnostics.AddError("Failed to create user", "cannot set password for LDAP user")
		return
	}
	if !ldapUser && password == "" {
		resp.Diagnostics.AddError("Failed to create user", "password is required for non-LDAP user")
		return
	}

	// api_key_raw is only set when a key is generated below.
	if plan.APIKeyRaw.IsUnknown() {
		plan.APIKeyRaw = types.StringNull()
	}

	// Check if user already exists
	userList, err := listUsers(ctx, client)
	if err != nil {
		resp.Diagnostics.AddError("Failed to create user", fmt.Sprintf("failed to list users: %s", err))
		return
	}
	for _, u := range userList {
		if u.Username == username {
			// Adopted: updated as if every configured attribute changed
			// from nothing.
			plan.ID = types.StringValue(strconv.FormatInt(u.ID, 10))
			prior := userResourceModel{Password: types.StringNull(), TeamID: types.Int64Null()}
			r.update(ctx, &plan, prior, &resp.Diagnostics)
			if resp.Diagnostics.HasError() {
				return
			}
			r.setAfterApply(ctx, &plan, &resp.State, &resp.Diagnostics)
			return
		}
	}

	createBody := struct {
		Username string  `json:"username"`
		Password *string `json:"password"`
		Role     int64   `json:"role"`
	}{Username: username, Role: role}
	if !ldapUser {
		createBody.Password = &password
	}

	var created portainerUser
	if err := doJSON(ctx, client, http.MethodPost, client.Endpoint+"/users", createBody, &created); err != nil {
		resp.Diagnostics.AddError("Failed to create user", fmt.Sprintf("failed to create user: %s", err))
		return
	}

	plan.ID = types.StringValue(strconv.FormatInt(created.ID, 10))
	// The user exists from here on: keep it in state even when a later step
	// fails, as SDKv2 did once the ID was set.
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), plan.ID)...)

	if teamID := plan.TeamID.ValueInt64(); teamID != 0 {
		if role != 2 {
			resp.Diagnostics.AddError("Failed to create user", "team_id can only be used with standard users (role = 2)")
			return
		}
		if err := updateUserTeam(ctx, client, int(created.ID), 0, int(teamID)); err != nil {
			resp.Diagnostics.AddError("Failed to create user", err.Error())
			return
		}
	}

	if plan.GenerateAPIKey.ValueBool() {
		description := plan.APIKeyDescription.ValueString()
		if password == "" {
			resp.Diagnostics.AddError("Failed to create user", "password must be set to generate API key")
			return
		}

		// Authenticate as new user
		authBody := struct {
			Username string  `json:"username"`
			Password string  `json:"password"`
			APIKey   *string `json:"apiKey"`
		}{Username: username, Password: password}
		var authResp struct {
			JWT string `json:"jwt"`
		}
		if err := doJSON(ctx, client, http.MethodPost, client.Endpoint+"/auth", authBody, &authResp); err != nil {
			resp.Diagnostics.AddError("Failed to create user", fmt.Sprintf("failed to authenticate as new user: %s", err))
			return
		}

		// Portainer only creates an API key for the user it authenticates, so
		// this request carries the new user's JWT instead of the provider's
		// credentials.
		userClient := &APIClient{Endpoint: client.Endpoint, JWTToken: authResp.JWT, HTTPClient: client.HTTPClient}
		keyBody := struct {
			Description string `json:"description"`
			Password    string `json:"password"`
		}{Description: description, Password: password}
		var keyResp struct {
			RawAPIKey string `json:"rawAPIKey"`
		}
		if err := doJSON(ctx, userClient, http.MethodPost, fmt.Sprintf("%s/users/%d/tokens", client.Endpoint, created.ID), keyBody, &keyResp); err != nil {
			resp.Diagnostics.AddError("Failed to create user", fmt.Sprintf("failed to generate API key: %s", err))
			return
		}
		plan.APIKeyRaw = types.StringValue(keyResp.RawAPIKey)
	}

	r.setAfterApply(ctx, &plan, &resp.State, &resp.Diagnostics)
}

// setAfterApply reads the user back into the model and stores it.
func (r *userResource) setAfterApply(ctx context.Context, m *userResourceModel, state *tfsdk.State, diags *diag.Diagnostics) {
	found := r.read(ctx, m, diags)
	if diags.HasError() {
		return
	}
	if !found {
		diags.AddError("Failed to read user", fmt.Sprintf("user %s disappeared right after it was written", m.ID.ValueString()))
		return
	}
	diags.Append(state.Set(ctx, m)...)
}

// read refreshes the model from the API; false when the user is gone.
func (r *userResource) read(ctx context.Context, m *userResourceModel, diags *diag.Diagnostics) bool {
	client := r.client
	id, _ := strconv.ParseInt(m.ID.ValueString(), 10, 64)

	var user portainerUser
	if err := doJSON(ctx, client, http.MethodGet, fmt.Sprintf("%s/users/%d", client.Endpoint, id), nil, &user); err != nil {
		if isAPINotFound(err) {
			return false
		}
		diags.AddError("Failed to read user", fmt.Sprintf("failed to read user: %s", err))
		return false
	}

	m.Username = types.StringValue(user.Username)
	m.Role = types.Int64Value(user.Role)
	m.CreatedAuthenticationMethod, m.LastAuthenticationMethod = userAuthMethodValues(user)
	// team_id tracks only the membership this resource manages. Other
	// memberships (portainer_team_membership) would otherwise show up as a
	// team_id the configuration does not have.
	if teamID := m.TeamID.ValueInt64(); teamID != 0 {
		membership, err := findUserTeamMembership(ctx, client, int(id), int(teamID))
		if err != nil {
			diags.AddError("Failed to read user", err.Error())
			return false
		}
		if membership == nil {
			m.TeamID = types.Int64Null()
		}
	}
	return true
}

func (r *userResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	fwSetIDIdentity(ctx, req.State, resp.Identity, &resp.Diagnostics)
	var state userResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	found := r.read(ctx, &state, &resp.Diagnostics)
	if resp.Diagnostics.HasError() {
		return
	}
	if !found {
		resp.State.RemoveResource(ctx)
		return
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *userResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	defer func() { fwSetIDIdentity(ctx, resp.State, resp.Identity, &resp.Diagnostics) }()
	var plan, state userResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	plan.ID = state.ID
	r.update(ctx, &plan, state, &resp.Diagnostics)
	if resp.Diagnostics.HasError() {
		return
	}
	r.setAfterApply(ctx, &plan, &resp.State, &resp.Diagnostics)
}

// update applies the plan to an existing user; prior is what is known of it.
func (r *userResource) update(ctx context.Context, plan *userResourceModel, prior userResourceModel, diags *diag.Diagnostics) {
	client := r.client
	id, _ := strconv.ParseInt(plan.ID.ValueString(), 10, 64)

	// Checked before anything is changed, so a rejected team_id does not
	// leave the user half-updated.
	if plan.TeamID.ValueInt64() != 0 && plan.Role.ValueInt64() != 2 {
		diags.AddError("Failed to update user", "team_id can only be used with standard users (role = 2)")
		return
	}

	if oldPw, newPw := prior.Password.ValueString(), plan.Password.ValueString(); oldPw != newPw {
		// Skip password update when old password is unknown (e.g. after import).
		// The Portainer API requires the current password to change it.
		if oldPw != "" && newPw != "" {
			pwBody := struct {
				Password    string `json:"password"`
				NewPassword string `json:"newPassword"`
			}{Password: oldPw, NewPassword: newPw}
			if err := doJSON(ctx, client, http.MethodPut, fmt.Sprintf("%s/users/%d/passwd", client.Endpoint, id), pwBody, nil); err != nil {
				diags.AddError("Failed to update user", fmt.Sprintf("failed to update password: %s", err))
				return
			}
		}
	}

	// newPassword and password are sent as null: the password is changed
	// through PUT /users/{id}/passwd above.
	updateBody := struct {
		Username    string  `json:"username"`
		Role        int64   `json:"role"`
		UseCache    bool    `json:"useCache"`
		NewPassword *string `json:"newPassword"`
		Password    *string `json:"password"`
	}{Username: plan.Username.ValueString(), Role: plan.Role.ValueInt64(), UseCache: true}
	if err := doJSON(ctx, client, http.MethodPut, fmt.Sprintf("%s/users/%d", client.Endpoint, id), updateBody, nil); err != nil {
		diags.AddError("Failed to update user", fmt.Sprintf("failed to update user: %s", err))
		return
	}

	if oldTeam, newTeam := prior.TeamID.ValueInt64(), plan.TeamID.ValueInt64(); oldTeam != newTeam {
		if err := updateUserTeam(ctx, client, int(id), int(oldTeam), int(newTeam)); err != nil {
			diags.AddError("Failed to update user", err.Error())
			return
		}
	}
}

func (r *userResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state userResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	id, _ := strconv.ParseInt(state.ID.ValueString(), 10, 64)
	if err := doJSON(ctx, r.client, http.MethodDelete, fmt.Sprintf("%s/users/%d", r.client.Endpoint, id), nil, nil); err != nil && !isAPINotFound(err) {
		resp.Diagnostics.AddError("Failed to delete user", fmt.Sprintf("failed to delete user: %s", err))
	}
}

// ImportState accepts a numeric user ID or a username.
func (r *userResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	// An import block with identity carries the numeric ID.
	if req.ID == "" {
		fwImportIDOrIdentity(ctx, req, resp)
		return
	}
	if _, err := strconv.ParseInt(req.ID, 10, 64); err == nil {
		resource.ImportStatePassthroughID(ctx, path.Root("id"), req, resp)
		return
	}

	userList, err := listUsers(ctx, r.client)
	if err != nil {
		resp.Diagnostics.AddError("Failed to import user", fmt.Sprintf("failed to list users for import: %s", err))
		return
	}
	for _, u := range userList {
		if u.Username == req.ID {
			resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), strconv.FormatInt(u.ID, 10))...)
			return
		}
	}
	resp.Diagnostics.AddError("Failed to import user", fmt.Sprintf("user %s not found", req.ID))
}
