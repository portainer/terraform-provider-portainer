var (
	_ resource.Resource                = (*userResource)(nil)
	_ resource.ResourceWithConfigure   = (*userResource)(nil)
	_ resource.ResourceWithImportState = (*userResource)(nil)
	_ resource.ResourceWithIdentity    = (*userResource)(nil)
)

func newUserResource() resource.Resource { return &userResource{} }

type userResource struct {
	fwIDIdentity
	client *APIClient
}

type userResourceModel struct {
	ID                          types.String `tfsdk:"id"`
	Username                    types.String `tfsdk:"username"`
	Password                    types.String `tfsdk:"password"`
	Role                        types.Int64  `tfsdk:"role"`
	LDAPUser                    types.Bool   `tfsdk:"ldap_user"`
	TeamID                      types.Int64  `tfsdk:"team_id"`
	GenerateAPIKey              types.Bool   `tfsdk:"generate_api_key"`
	APIKeyDescription           types.String `tfsdk:"api_key_description"`
	APIKeyRaw                   types.String `tfsdk:"api_key_raw"`
	CreatedAuthenticationMethod types.String `tfsdk:"created_authentication_method"`
	LastAuthenticationMethod    types.String `tfsdk:"last_authentication_method"`
}

